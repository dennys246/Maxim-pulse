#!/usr/bin/env node
/**
 * Emit the contract version the generated client was built against, as a TS
 * constant the UI can compare against a live backend's
 * `/api/identity.contract_version` — catching a UI built for a different API
 * than the server actually speaks.
 *
 * Runs as part of `pnpm gen:facade`. Paths resolve from THIS FILE, not the
 * CWD, because pnpm runs package scripts inside the package directory.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const contract = join(repoRoot, 'packages/kit/openapi.json')
const out = join(repoRoot, 'packages/kit/src/facade/contractVersion.ts')

const version = JSON.parse(readFileSync(contract, 'utf8')).info?.version ?? 'unknown'
writeFileSync(
  out,
  `/**
 * Generated by \`pnpm gen:facade\` — do not edit.
 *
 * The \`maxim serve\` contract these types were generated from. Compared
 * against a live backend's /api/identity.contract_version so a UI built for a
 * different API than the server speaks says so, loudly.
 */
export const CONTRACT_VERSION = '${version}'
`,
)
console.log(`gen:facade — contractVersion.ts = ${version}`)
